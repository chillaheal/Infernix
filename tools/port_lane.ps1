<#
.SYNOPSIS
    Replay the image lane onto an upstream Infernix checkout, driven by the seam manifest.

.DESCRIPTION
    This is the port driver for docs/maintainer/image-integration-points.md. It does the part of a
    port that is mechanical, and it refuses the part that is not:

      1. It runs tools/check_image_seams.py against <Upstream> and stops on any missing must-port
         anchor or broken seam. A port never starts from a build error.
      2. It copies every ours-only lane file (the manifest's ours-only rows, plus each row's
         companions) into the target checkout. These have no upstream counterpart, so copying is all
         there is.
      3. For every upstream-owned file the lane touches it writes one patch per row with
         "git diff <Upstream> <OurRef> -- <path>" (the only primitive that works here: this fork and
         upstream share no merge-base, but both blobs live in this one object DB) into
         <Target>\.image-port\patches\, in a fixed order, and -- when -Apply is given - applies each
         with "git apply --3way". A patch that does not apply is NOT forced: the file is reported in
         NEEDS_MANUAL together with the manifest row's "does:" text, which says where to re-anchor it.
      4. With -Build it runs the sanctioned runners (the same _p40_*.bat files the lane is tested
         with) and reports their own exit codes.

    It commits nothing, touches nothing outside <Target>\.image-port\ and the files it is told to
    write, and never starts, stops or copies over a running infernix-serve.

    The hard seams (src/models/qwen4_exp/program/program_impl.h and the residency/VRAM contract) are
    re-derivation work, not merge work: expect them in NEEDS_MANUAL and budget days, not minutes.

.EXAMPLE
    py -3.13 -I tools\check_image_seams.py --upstream f9c2e42c --offline
    powershell -NoProfile -ExecutionPolicy Bypass -File tools\port_lane.ps1 -Target C:\temp\upstream-checkout -Upstream f9c2e42cb3e9 -DryRun
    powershell -NoProfile -ExecutionPolicy Bypass -File tools\port_lane.ps1 -Target C:\temp\upstream-checkout -Apply
#>
[CmdletBinding()]
param(
    [string]$Upstream = 'f9c2e42cb3e9',
    [Parameter(Mandatory = $true)][string]$Target,
    # Pass -OurRef '' to port the working tree as it stands (uncommitted seam work included); any
    # other value is a ref name and ports that commit.
    [string]$OurRef = 'HEAD',
    [string]$Manifest = 'docs/maintainer/image-integration-points.md',
    # The ours-only copy set, generated by tools/image_lane_copy_set.py from CMake's generated projects.
    [string]$CopySet = 'docs/maintainer/image-lane.copy-set.json',
    # Upstream-owned files a person ports by hand instead of by patch: on this fork these are the shared
    # contracts where the fork trails upstream's own refactors, so no mechanical hunk selection can say
    # which line is the lane's. The driver reports each one under NEEDS_MANUAL with the manifest's own
    # "does:" text; docs/maintainer/image-integration-points.md says what the lane needs from each.
    [string[]]$Manual = @(),
    # Copies only: no patch is applied and every upstream-owned row is reported as hand-ported. Used when
    # the target must keep upstream's own shape of the shared contracts and the lane's registration is
    # being placed by hand.
    [switch]$CopiesOnly,
    [string]$Python = 'py',
    [string[]]$PythonFlags = @('-3.13', '-I'),
    [switch]$SkipSeamCheck,
    [switch]$Apply,
    [switch]$DryRun,
    [switch]$Build,
    [string]$BuildDir = '',
    [string]$Artifact = '',
    [string]$LegacyArtifact = '',
    [string]$Oracle = ''
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

function Invoke-Tool {
    param([string]$File, [string[]]$Arguments)
    $previous = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        $out = & $File @Arguments 2>&1
        $code = $LASTEXITCODE
    } finally { $ErrorActionPreference = $previous }
    return [pscustomobject]@{ Code = $code; Lines = @($out) }
}

function Invoke-Git {
    param([string]$Repo, [string[]]$Arguments)
    return Invoke-Tool -File 'git' -Arguments (@('-C', $Repo) + $Arguments)
}

function Fail([string]$Message) {
    Write-Host "PORT_ABORT: $Message"
    exit 2
}

$Repo = (Invoke-Git -Repo '.' -Arguments @('rev-parse', '--show-toplevel'))
if ($Repo.Code -ne 0) { Fail 'not a git repository (git rev-parse --show-toplevel failed)' }
$Repo = ($Repo.Lines | Select-Object -First 1).Trim()
Write-Host "repo    : $Repo"

if (-not (Test-Path -LiteralPath $Target)) { Fail "target checkout not found: $Target" }
$Target = (Resolve-Path -LiteralPath $Target).Path

$resolveUp = Invoke-Git -Repo $Repo -Arguments @('rev-parse', '--verify', '--quiet', "$Upstream^{commit}")
if ($resolveUp.Code -ne 0 -or -not $resolveUp.Lines) {
    Fail "upstream ref '$Upstream' is not present locally; fetch it first (this script never touches the network)"
}
$UpstreamSha = ($resolveUp.Lines | Select-Object -First 1).Trim()
Write-Host "upstream: $Upstream -> $($UpstreamSha.Substring(0,12))"

$resolveTarget = Invoke-Git -Repo $Target -Arguments @('rev-parse', '--verify', '--quiet', 'HEAD')
if ($resolveTarget.Code -ne 0) { Fail "target is not a git checkout: $Target" }
$TargetSha = ($resolveTarget.Lines | Select-Object -First 1).Trim()
if ($TargetSha -ne $UpstreamSha) {
    Write-Host "PORT_NOTE: target HEAD $($TargetSha.Substring(0,12)) is not the upstream ref $($UpstreamSha.Substring(0,12));"
    Write-Host '           patches are computed against the upstream ref, so a moved target will conflict. That is the'
    Write-Host '           intended signal - do not force it, resolve and re-run.'
}

$work = Join-Path $Target '.image-port'
$patchDir = Join-Path $work 'patches'
if (-not $DryRun) {
    New-Item -ItemType Directory -Force -Path $patchDir | Out-Null
}
$planPath = Join-Path $work 'plan.json'

# 1. The manifest is the contract: the checker runs before anything is copied or applied.
if (-not $SkipSeamCheck) {
    $check = Invoke-Tool -File $Python -Arguments ($PythonFlags + @('tools/check_image_seams.py',
            '--upstream', $Upstream, '--offline', '--manifest', $Manifest))
    $check.Lines | ForEach-Object { Write-Host $_ }
    if ($check.Code -eq 1) { Fail 'a must-port anchor is missing or a seam is broken - fix the manifest row first, do not start a port from here' }
    if ($check.Code -ne 0) { Fail "the seam checker exited $($check.Code) (manifest unusable or refs unresolved)" }
}
New-Item -ItemType Directory -Force -Path $work | Out-Null
$emit = Invoke-Tool -File $Python -Arguments ($PythonFlags + @('tools/check_image_seams.py',
        '--upstream', $Upstream, '--offline', '--manifest', $Manifest, '--emit-plan', $planPath))
if ($emit.Code -ne 0) { Fail 'could not emit the port plan from the manifest' }
$plan = (Get-Content -LiteralPath $planPath -Raw -Encoding UTF8 | ConvertFrom-Json).rows
Write-Host "plan    : $($plan.Count) rows from $Manifest"

# 2. Ours-only lane files: a pure copy, headers included.
#
# The manifest's ours-only rows are the documentation; the authority for WHAT must be copied is
# docs/maintainer/image-lane.copy-set.json, generated by tools/image_lane_copy_set.py from CMake's own
# generated projects (it follows the target file lists and the #include closure, so it catches every
# header, .cu kernel and fixture a lane target reaches). The union is copied, and with -BuildDir given
# the JSON is checked for staleness first so a lane file added after the last regeneration cannot be
# silently left behind.
if (-not $SkipSeamCheck) {
    # Derive from THIS tree's configured build dir: the generated projects that describe the lane live
    # here, next to the sources being ported. -BuildDir names the target's build dir for the runners
    # and is not the same thing.
    $oursBuild = Join-Path $Repo 'build-windows'
    if (-not (Test-Path -LiteralPath $oursBuild)) { Fail "no build directory at ${oursBuild} -- configure this checkout first, the copy set is derived from CMake's generated projects" }
    $csArgs = $PythonFlags + @('tools/image_lane_copy_set.py', '--upstream', $Upstream, '--check',
                               '--build-dir', $oursBuild)
    $cs = Invoke-Tool -File $Python -Arguments $csArgs
    $cs.Lines | ForEach-Object { Write-Host $_ }
    if ($cs.Code -ne 0) { Fail 'the ours-only copy set is stale or a listed file is gone -- rerun tools/image_lane_copy_set.py --write-json before porting' }
}
$copySetPath = Join-Path $Repo ($CopySet -replace '/', '\')
if (-not (Test-Path -LiteralPath $copySetPath)) { Fail "missing $CopySet -- generate it with tools/image_lane_copy_set.py --write-json" }
$copyPaths = @((Get-Content -LiteralPath $copySetPath -Raw -Encoding UTF8 | ConvertFrom-Json).files)
foreach ($row in $plan | Where-Object { $_.category -eq 'ours-only' }) {
    $copyPaths += @($row.our_path) + @($row.companions)
}
$copied = 0
$missingSource = @()
$done = @{}
foreach ($path in $copyPaths) {
    if (-not $path) { continue }
    if ($done.ContainsKey($path)) { continue }
    $done[$path] = $true
    $from = Join-Path $Repo ($path -replace '/', '\')
    if (-not (Test-Path -LiteralPath $from)) { $missingSource += $path; continue }
    $to = Join-Path $Target ($path -replace '/', '\')
    if ($DryRun) { Write-Host "DRYRUN copy  $path"; $copied++; continue }
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $to) | Out-Null
    Copy-Item -LiteralPath $from -Destination $to -Force
    $copied++
}
Write-Host "copied  : $copied ours-only lane file(s)"
if ($missingSource.Count) {
    foreach ($m in $missingSource) { Write-Host "PORT_MISSING_SOURCE: $m" }
    Fail 'an ours-only row names a file that is not in this tree'
}

# 3. The lane-only patch series, then --3way when told to apply.
#
# The patches come from tools/image_lane_patch_series.py, deliberately NOT from a raw
# "git diff <upstream> <our-ref> -- <path>". That diff is the whole fork -- about 5900 added lines of
# which roughly 11% mention the lane -- so applying it over upstream's newer code replaces upstream
# refactors with the fork's older shape. The first lane-only port died exactly there: the fork's
# include/infernix/types.h took the place of upstream's kv_format.h refactor and every consumer failed
# to compile. The tool keeps only hunks whose changed lines name lane code, so what crosses is the lane.
$ordered = $plan | Where-Object { $_.category -ne 'ours-only' } | Sort-Object { $_.our_path }
if ($DryRun) {
    foreach ($row in $ordered) { Write-Host "DRYRUN patch $($row.upstream_path) ($($row.category), $($row.hunks) hunks)" }
    Write-Host ''
    Write-Host 'PORT_RESULT: OK (dry run - no patch was applied)'
    exit 0
}
if (-not $CopiesOnly) {
    if (Test-Path -LiteralPath $patchDir) { Remove-Item -LiteralPath $patchDir -Recurse -Force }
    New-Item -ItemType Directory -Force -Path $patchDir | Out-Null
    $seriesArgs = $PythonFlags + @('tools/image_lane_patch_series.py', '--upstream', $Upstream,
                                   '--plan', $planPath, '--out', $patchDir)
    if ($OurRef) { $seriesArgs += @('--our-ref', $OurRef) } else { $seriesArgs += @('--working-tree') }
    $series = Invoke-Tool -File $Python -Arguments $seriesArgs
    $series.Lines | ForEach-Object { Write-Host $_ }
    if ($series.Code -ne 0) { Fail "the lane patch series failed (exit $($series.Code))" }
}

$applied = @(); $needsManual = @(); $empty = @()
$skippedManual = @()
foreach ($row in $ordered) {
    if ($CopiesOnly -or $Manual -contains $row.upstream_path) { $skippedManual += $row.upstream_path; continue }
    $suffix = ($row.upstream_path -replace '[\\/]', '_') + '.patch'
    $found = @(Get-ChildItem -LiteralPath $patchDir -Filter "*-$suffix" -ErrorAction SilentlyContinue)
    if (-not $found -or (Get-Item -LiteralPath $found[0].FullName).Length -eq 0) {
        $empty += $row.upstream_path; continue
    }
    $patchPath = $found[0].FullName
    if (-not $Apply) { continue }
    $gitApply = Invoke-Git -Repo $Target -Arguments @('apply', '--3way', '--whitespace=nowarn', $patchPath)
    if ($gitApply.Code -eq 0) { $applied += $row.upstream_path }
    else { $needsManual += @{ row = $row; why = "git apply --3way exited $($gitApply.Code)" } }
}

Write-Host ''
Write-Host "patches : $($ordered.Count) written to $patchDir"
if ($Apply) { Write-Host "applied : $($applied.Count) clean, $($needsManual.Count) needing a person" }

# 4. What a person must re-derive, with the manifest's own instruction beside each file.
if ($skippedManual.Count) {
    Write-Host ''
    Write-Host 'HAND-PORTED (left at upstream tip on purpose - the shared contracts this fork trails;'
    Write-Host '           add what the lane needs by hand, see docs/maintainer/image-integration-points.md):'
    foreach ($p in $skippedManual) { Write-Host "  $p" }
}
if ($needsManual.Count) {
    Write-Host ''
    Write-Host 'NEEDS_MANUAL (do not force these; the row tells you where the hunk belongs):'
    foreach ($item in $needsManual) {
        $row = $item.row
        Write-Host ("  {0}  [{1}, hunks={2}]  {3}" -f $row.upstream_path, $row.category, $row.hunks, $item.why)
        foreach ($anchor in $row.anchors) { Write-Host "      anchor: $anchor" }
        $does = [string]$row.does
        if ($does.Length -gt 0) {
            $text = if ($does.Length -gt 400) { $does.Substring(0, 400) + ' ...' } else { $does }
            Write-Host "      does  : $text"
        }
    }
}
if ($empty.Count) {
    Write-Host ''
    Write-Host "no lane change against the upstream ref for: $($empty -join ', ') (a row whose upstream side moved to a new path)"
}

# 5. The build and the host suites, through the sanctioned runners only.
if ($Build) {
    if (-not $BuildDir -or -not $Artifact -or -not $Oracle) {
        Fail '-Build needs -BuildDir, -Artifact and -Oracle (the sanctioned runners take the real paths; nothing is guessed here)'
    }
    $runners = Join-Path (Split-Path -Parent $Repo) 'image-edit'
    $buildBat = Join-Path $runners '_p40_build_only.bat'
    $suitesBat = Join-Path $runners '_p40_host_suites.bat'
    foreach ($bat in @($buildBat, $suitesBat)) {
        if (-not (Test-Path -LiteralPath $bat)) { Fail "sanctioned runner missing: $bat" }
    }
    if ($DryRun) { Write-Host 'DRYRUN build (skipped)'; exit 0 }
    Write-Host "build   : $buildBat $BuildDir infernix-serve 6"
    & $buildBat $BuildDir infernix-serve 6
    if ($LASTEXITCODE -ne 0) { Fail "the sanctioned build exited $LASTEXITCODE" }
    $targets = @('infernix_http_routes_test', 'infernix_http_error_handler_test', 'infernix_http_transport_test',
        'infernix_image_generation_service_test', 'infernix_serve_options_test', 'infernix_openai_schema_test',
        'infernix_openai_images_schema_test', 'infernix_openai_responses_test', 'infernix_openai_responses_store_test',
        'infernix_chat_image_tool_test', 'infernix_anthropic_schema_test', 'infernix_image_job_store_test',
        'infernix_image_joint_limits_test', 'infernix_prompt_enhancer_test', 'infernix_image_device_need_test',
        'infernix_media_encode_test')
    Write-Host "suites  : $($targets.Count) host targets"
    & $suitesBat $Artifact $LegacyArtifact $Oracle @targets
    if ($LASTEXITCODE -ne 0) { Fail "the sanctioned host suites exited $LASTEXITCODE" }
}

Write-Host ''
Write-Host 'PORT_RESULT: OK'
if (-not $Apply) { Write-Host '  (patches were written, not applied - re-run with -Apply, then resolve every NEEDS_MANUAL file by hand)' }
exit 0
